'use strict'
/**
 * 导演手册里「写 prompt」和「看片子」这两段正文。
 *
 * 为什么要把长文放进代码而不是让模型自己发挥：这两段是踩出来的具体判断，
 * 一句话 prompt 出的是「图」，十段 prompt 出的是「照片」；差别不在模型，
 * 在于有没有把相机真会记录下来的物理事实写进去。这些约束写进工具返回值，
 * 模型每轮都读得到，不用靠记性。
 */

/** 写真照片级 prompt 的十段契约。 */
function imagePromptGuide() {
  return `【照片级 prompt 的十段契约】
按顺序写成十个自然段，250–400 字。少于 250 字信息不够，超过 400 字后面几段会被稀释。

1 画框：什么介质 + 谁/什么 + 在做什么 + 相机站在哪。最后加一句「视线从哪里进、落在哪里」。
2 瞬间：写的是「哪半秒」，不是「在干什么」。「他刚停下扳手、偏头听压缩机，手还搭在工具上」——峰值动作前一拍或后一拍，照片都活在那里。
3 光：先一句时辰/季节/天气这个物理事实，再把每个光源和质量写清（主光、补光、实用光、反弹光），给出**主光与补光的档数比**，最后一句说这束光在这一帧里在干什么。混色温看起来才真。
4 相机：机位高度、距离、角度。机身级别 + 焦段 + 光圈。**成像性格**——扩散、耀斑、焦外形状、颗粒、暗角；哪一层是实焦、虚得有多快。有动作就写快门。
5 构图：前/中/后景分层。主体靠什么和背景分开——靠明度、靠颜色还是靠焦点，说出是哪一种。主体占比、留白、视线空间。**边缘纪律：不许有任何东西贴着画框边，也不许背景线条从头上升出来。**
6 环境：这个真实地点该有的具体物件，摊在三层里。要有杂物和实用性，不许摆拍。**至少放一件对这个画面没用的东西**——真照片里都有。
7 主体真实：衣服的具体款式/合身度/新旧/垂坠。然后是人的物理：不对称的微表情、视线看向哪、看向什么、手在做什么、重心在哪只脚。画面里没人就换成「材质与表面」——基底、工艺、年岁、光在每种表面上怎么走。
8 瑕疵：**至少五个具体缺陷**，从皮肤/织物/空气/表面/光学/环境里至少挑三类。这一段不能省——省了必出塑料感。
9 Punctum：**恰好一个**微小、具体、微微不合逻辑的细节，让这一帧只能是这一帧——设备门内侧贴的一张小孩画、一只不配对的袜子、工作手套外面的婚戒。不是缺陷，是背后有故事的事实。
10 色调与参考：先写颜色的**关系**（互补/邻近/近乎单色加一处高饱和/分离色调），再用 4–6 个真实色名落实。点一个胶片型号或调色参考。最后是负面清单：不要 CGI 感、不要塑料蜡像皮肤、不要美颜磨皮、不要过度锐化、不要 HDR 光晕、不要无来由的对称、手不许畸变、不加文字水印。

【为什么一句话出不来】
「AC 维修场景，对称构图，从机器内部拍」→ 出一张泛泛的库存图。
把它展开成相机真的会记录下来的物理事实 → 出一张照片。
再展开成摄影师会做的判断 → 出一张好照片。

两个轴，不是一个：
· 真实性——相机会不会拍到这个？（第 3、4、7、8 段负责）
· 值得看——这一帧值不值得看？（第 2、5、9、10 段负责）
只顾真实性 → 一张可信的库存照：真，但无聊。
只顾好看 → 一张 CGI 海报：亮，但假。

**真实感来自约束，不来自形容词。**「photorealistic, 8k, ultra detailed」是噪音；一个具体型号的镜头、一个具体的光源、一个具体的缺陷、一种具体材质，才是信号。
**值得看来自下注。** 一个瞬间、一个光的主意、一个不可能在别处的细节。

【定一个主意，别做好几个】
「戏剧化又柔和」「广又亲密」「阴郁又明亮」——模型会把互相矛盾的指令平均成一团浆糊。先定下这个主意，然后让每一段都为它服务。

【最常犯的错】
· 堆质量词（8k/超清/杰作）→ 删掉，把字数花在光、瞬间、瑕疵上
· 跳过第 8 段 → 必出塑料 CGI 感
· 跳过第 2、9 段 → 技术上完美，完全记不住（库存图的死法）
· 写「在修空调」而不是「哪半秒」→ 把所有瞬间平均成一个都没有
· 列六个颜色而不是一个颜色关系 → 平均成泥
· 罗列灯而不说光在干什么 → 一张灯的单子不是布光
· 自相矛盾（黄金时刻 + 阴天 + 硬阴影）→ 平均成浆糊
· 机位含糊（「好角度」）→ 高度、距离、看见什么，都得说
· AI 味陈词：青橙调、无来由的双侧轮廓光、到处湿地面、每道光柱里都有尘埃、画面里没有光源却有耀斑
· 写真人姓名或商标 → 描述类型：「没有品牌标志的工装」
· 生成一次就交 → 先用最终要用的模型出两张，看过，只改最差的那一处，再出

【出一张之后怎么改】（只改一处，别重写）
· 全都一样清 → 第 4 段：给大光圈 f/1.4–2.8，写明哪层实焦、什么在虚
· 皮肤蜡像感 → 第 8 段：再补三个具体皮肤缺陷；第 7 段写「脸颊和鼻头看得见毛孔，肤色不匀」
· 平、没劲 → 第 3 段：给档数比 4:1 或 8:1，把补光杀掉，「相机右侧没有补光，那侧压到近黑」
· 颜色发泥 → 第 10 段：先写关系再写色调
· 主体糊进背景 → 第 5 段：说出分离机制，「他背后的浅色墙面亮两档，把肩线衬成剪影」
· 摆拍感 → 第 6 段加一件没用的东西；第 2 段把瞬间挪离峰值
· 太泛 → 第 9 段：punctum 丢了或太虚，换成一个有暗示历史的实物
· 边上有切线 → 第 5 段：「门框离他头顶还有一掌，没有线条碰画框边」
· 对称 AI 脸 → 第 7 段：「不对称表情，一边眉毛略高，重心在左脚，正在眨眼中间」
· 构图无聊 → 第 1 段换机位，不换词——从门框里、越过肩膀、从台面下方、玻璃反射里
· 文字乱码 → 缩短到五个词以内并原样引号，或换更擅长文字的模型
· 手不对 → 第 7 段给手一个具体任务并写握法：「左手平撑在面板上，右手握住扳手柄」

改两轮就停。第二处修完还不对，问题在主意不在措辞——回去重选那个 look 和那个瞬间。

【光必须写成一句能量出来的话】
「自然光」「光线好」「打光专业」这些词对模型等于没写，它只会补回那套影棚感。
句式固定：从哪来 + 什么质感 + 什么时辰 + 影子落在哪。
· 「午后窗光从左边进来，右脸落下自然的暗面」
· 「阴天平光，没有硬影」「黄昏 45 度侧光，暖调，影子拉长」
· 「顶光正午，下巴下一道短而深的影」
· 近景与中景一定加眼神光：虹膜里有那点亮，眼睛才活着；不加就是死鱼眼。
· 想让人从背景里立出来：发丝上一点轮廓光，或肩线一道细边光。
· 要冷要暖直接说色温：暖 3200K 钨丝、冷 5600K 日光，或「室内暖 + 窗外冷」。
· 别单独写「电影感」——它已经被用烂了。要说清是侧硬光加深影，还是低反差平光。`
}

/** 看图的评分底稿：两条轴、十四项。 */
function imageReviewPrompt(shot) {
  let text = '这是我刚生成的一张图，你当摄影指导给我挑。\n'
  if (shot) text += `\n我原本想要的是：${String(shot).slice(0, 400)}\n`
  return text + `
先看真实性这条轴（相机会不会拍到这个），七项：
1 光源故事——所有影子的方向、硬度、颜色是一致的一套吗？有没有两个方向的影子、同一束光既软又硬、脸被照亮但别处没有相应的高光？
2 眼神光与灯具是否匹配——窗是矩形、柔光箱是圆、实用光是点、阴天是宽而暗。屋里只有一扇窗却有两个一样的圆形眼神光就是假的。
3 选择性锐度——有没有一个焦平面？全都一样清是最可靠的渲染破绽。
4 皮肤——有没有毛孔、不对称、耳鼻指靠近光的次表面散射、T 区皮脂？蜡、磨皮、肤色均匀、没有毛孔的脸颊、对称的脸，都是不合格。
5 四个失败区——手、文字、反射、眼睛。手指多一根或黏在一起、字乱码、反射和画面前景对不上、两个瞳孔不一样。
6 材质行为——金属有没有各向异性拉丝、织物有没有织纹和重力垂坠、玻璃有没有厚度和折射、物体接触处有没有阴影。物体浮在表面上空一毫米、金属像塑料、织物没有重量，都不合格。
7 尺度与透视——物体大小和地平线跟机位对得上吗？广角构图配长焦压缩、家具尺寸不对、两个消失点打架。

再看值得看这条轴（这一帧值不值得看），七项：
8 主体与背景分离——靠明度、颜色还是焦点站出来的？深色夹克融进深色背景、整张图读成一片纹理而不是一个主体，都不合格。
9 边缘纪律——有没有东西贴着画框边、有没有背景线条从头上升出来、有没有肢体在关节处被裁掉。未解决的切线是最常见的外行破绽。
10 瞬间可见——你能说出刚刚发生了什么吗？人摆着什么也没做、把一个活动平均成了没有瞬间，不合格。
11 景深分层——前景、中景、背景是不是都有东西？主体贴在背景板上、该三层只有两层。
12 配色层级——是主导+支撑+点缀，还是六个颜色同权重的泥？
13 那个怪细节还在吗——我本来想要一个微小具体、微微不合逻辑但背后有故事的细节，它真的在画面里吗？
14 你会把它留在剪辑里吗——说不出要改哪一处，说明你没认真看。

说话方式：
· 先给一句判断：这张能用、能用但要改一处、还是不能用。
· 然后只指出**唯一最差的那一处**，并说清该改 prompt 的第几段、怎么改。不要列十条，列十条等于没重点——改的时候只能改一处。
· 如果问题看起来出在模型而不是 prompt（比如皮肤整体蜡感、字全乱），直接说「这是模型的问题，换一个生图模型再来」，不要去改 prompt。
· 只说你真看得出来的。看不出来就说看不出来，不要凑数。`
}

module.exports = { imagePromptGuide, imageReviewPrompt }
